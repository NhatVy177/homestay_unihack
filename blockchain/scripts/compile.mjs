import solc from "solc";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

export const projectRoot = fileURLToPath(new URL("../", import.meta.url));
async function compile(contractName) {
  const sourceName = `contracts/${contractName}.sol`;
  const input = {
    language: "Solidity",
    sources: { [sourceName]: { content: await readFile(new URL(`../${sourceName}`, import.meta.url), "utf8") } },
    settings: {
      optimizer: { enabled: true, runs: 200 },
      evmVersion: "cancun",
      outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object", "metadata"] } },
    },
  };
  const output = JSON.parse(solc.compile(JSON.stringify(input), { import(name) {
    try {
      const content = readFileSync(resolve(projectRoot, 'node_modules', name), 'utf8');
      input.sources[name] = { content };
      return { contents: content };
    } catch { return { error: 'Import not found: ' + name }; }
  } }));
  for (const issue of output.errors ?? []) console.error(issue.formattedMessage);
  if ((output.errors ?? []).some((issue) => issue.severity === "error")) process.exit(1);
  const contract = output.contracts[sourceName][contractName];
  const artifact = {
    contractName, sourceName, compilerVersion: solc.version(),
    abi: contract.abi, bytecode: `0x${contract.evm.bytecode.object}`,
    deployedBytecode: `0x${contract.evm.deployedBytecode.object}`,
  };
  await mkdir(new URL("../artifacts/", import.meta.url), { recursive: true });
  await writeFile(new URL(`../artifacts/${contractName}.json`, import.meta.url), JSON.stringify(artifact, null, 2) + "\n");
  if (contractName === "DormSettlement") {
    await writeFile(new URL("../artifacts/standard-input.json", import.meta.url), JSON.stringify(input, null, 2) + "\n");
    await writeFile(new URL("../src/abi.js", import.meta.url), `// Generated by npm run compile from contracts/DormSettlement.sol.\nexport const abi = ${JSON.stringify(contract.abi, null, 2)};\n`);
  }
  console.log(`Compiled ${contractName} with solc ${solc.version()} (${contract.evm.bytecode.object.length / 2} bytes).`);
}

await compile("DormSettlement");
await compile("DormPoints");
