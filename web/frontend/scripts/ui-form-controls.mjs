import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';
const base = process.env.UI_BASE_URL || 'http://127.0.0.1:5205';
const folder = '.ui-screens/form-controls';
await mkdir(folder, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const report = [];
try {
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    const page = await context.newPage(), errors = [], writes = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/**', route => {
      if (!new URL(route.request().url()).pathname.startsWith('/api/')) return route.fallback();
      if (!['GET', 'HEAD', 'OPTIONS'].includes(route.request().method())) writes.push(route.request().method());
      return route.fulfill({ json: [] });
    });
    await page.goto(base, { waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: 'Đăng nhập', exact: true }).first().click();
    await page.getByRole('dialog').getByRole('button', { name: 'Đăng ký', exact: true }).click();
    const birthday = page.locator('input[name="ngaySinh"]');
    await birthday.fill('2000-02-29');
    await birthday.click();
    const popup = page.locator('#ui-control-popover');
    await popup.getByRole('button', { name: '28/02/2000', exact: true }).click();
    assert.equal(await birthday.inputValue(), '2000-02-28');
    await page.locator('input[name="hoTen"]').fill('Khách giao diện');
    assert.equal(await birthday.inputValue(), '2000-02-28', 'controlled React value persists after another field changes');
    await page.locator('select[name="gioiTinh"]').click();
    await popup.getByRole('option', { name: 'Nữ', exact: true }).click();
    assert.equal(await page.locator('select[name="gioiTinh"]').inputValue(), 'Nữ');
    await birthday.click();
    await popup.getByRole('button', { name: 'Chọn năm', exact: true }).click();
    await popup.getByRole('button', { name: '1999', exact: true }).click();
    await popup.getByRole('button', { name: 'Tháng 12', exact: true }).click();
    await popup.getByRole('button', { name: '31/12/1999', exact: true }).click();
    assert.equal(await birthday.inputValue(), '1999-12-31');
    await birthday.click();
    await page.screenshot({ path: `${folder}/register-calendar-${width}.png` });
    await page.keyboard.press('Escape');
    assert.equal(await popup.count(), 0);
    assert.equal(await page.getByRole('dialog').count(), 1, 'Escape closes picker before parent dialog');
    await birthday.focus();
    await page.keyboard.press('Alt+ArrowDown');
    await popup.getByRole('button', { name: 'Xóa chọn', exact: true }).click();
    assert.equal(await birthday.inputValue(), '');
    assert.equal(await birthday.evaluate(input => input.validity.valueMissing), true);
    await page.keyboard.press('Escape');

    // Dynamically mounted fields exercise the same boundary as every portal/modal.
    await page.evaluate(() => {
      const form = document.createElement('form'); form.id = 'control-fixture';
      form.innerHTML = '<label>Ngày sinh giới hạn<input type="date" max="2008-11-18" required></label><label>Ngày bước<input type="date" min="2026-11-18" max="2026-11-24" step="2"></label><label>Giờ xem<input type="time" min="07:00" max="17:00" step="900"></label><label>Ngày giờ<input type="datetime-local" min="2026-11-18T14:10" max="2026-11-19T09:10" step="900"></label><label>Chỉ đọc<input type="date" value="2026-11-18" readonly></label><label>Vô hiệu<input type="time" disabled></label><label>Chi nhánh<select><option value="">Chọn</option><option value="a">Chi nhánh A</option><option value="b" disabled>Chi nhánh B</option><option value="c">Chi nhánh C</option></select></label>';
      document.getElementById('root').after(form);
      form.addEventListener('submit', event => event.preventDefault());
      window.controlChanges = [];
      form.addEventListener('change', event => window.controlChanges.push({ type: event.target.type, value: event.target.value }));
    });
    const birth = page.getByLabel('Ngày sinh giới hạn', { exact: true });
    await page.evaluate(() => document.getElementById('control-fixture').insertAdjacentHTML('beforeend', '<fieldset id="inherited-lock" disabled><label>Ngày khóa theo nhóm<input type="date"></label><label>Nhóm khóa<select><option value="a">A</option><option value="b">B</option></select></label></fieldset>'));
    await page.locator('#inherited-lock input').dispatchEvent('click');
    assert.equal(await popup.count(), 0, 'disabled fieldset blocks custom date popup');
    await page.locator('#inherited-lock select').dispatchEvent('keydown', { key: 'ArrowDown' });
    assert.equal(await popup.count(), 0, 'disabled fieldset blocks custom select popup');
    await page.locator('#inherited-lock').evaluate(fieldset => { fieldset.disabled = false; });
    await page.locator('#inherited-lock select').click();
    await popup.getByRole('option', { name: 'B', exact: true }).waitFor();
    await page.locator('#inherited-lock').evaluate(fieldset => { fieldset.disabled = true; });
    await popup.getByRole('option', { name: 'B', exact: true }).click();
    assert.equal(await page.locator('#inherited-lock select').inputValue(), 'a', 'a fieldset locked while a popup is open cannot be changed');
    assert.equal(await popup.count(), 0);
    await birth.click();
    await popup.getByRole('button', { name: '18/11/2008', exact: true }).waitFor();
    assert.equal(await popup.getByRole('button', { name: '19/11/2008', exact: true }).isDisabled(), true);
    await popup.getByRole('button', { name: '18/11/2008', exact: true }).click();
    assert.equal(await birth.inputValue(), '2008-11-18');
    const stepped = page.getByLabel('Ngày bước', { exact: true });
    await stepped.click();
    assert.equal(await popup.getByRole('button', { name: '19/11/2026', exact: true }).isDisabled(), true);
    await popup.getByRole('button', { name: '20/11/2026', exact: true }).click();
    assert.equal(await stepped.inputValue(), '2026-11-20');
    const time = page.getByLabel('Giờ xem', { exact: true });
    await time.click();
    assert.equal(await popup.getByRole('group', { name: 'Giờ', exact: true }).getByRole('button').count(), 11);
    assert.deepEqual(await popup.getByRole('group', { name: 'Phút', exact: true }).getByRole('button').allTextContents(), ['00', '15', '30', '45']);
    await popup.getByRole('group', { name: 'Giờ', exact: true }).getByRole('button', { name: '16', exact: true }).click();
    await popup.getByRole('group', { name: 'Phút', exact: true }).getByRole('button', { name: '45', exact: true }).click();
    await page.screenshot({ path: `${folder}/time-${width}.png` });
    await popup.getByRole('button', { name: 'Chọn 16:45', exact: true }).click();
    assert.equal(await time.inputValue(), '16:45');
    assert.equal(await time.evaluate(input => input.validity.valid), true);
    const datetime = page.getByLabel('Ngày giờ', { exact: true });
    await datetime.click();
    await popup.getByRole('button', { name: '19/11/2026', exact: true }).click();
    await popup.getByRole('group', { name: 'Giờ', exact: true }).getByRole('button', { name: '09', exact: true }).click();
    assert.deepEqual(await popup.getByRole('group', { name: 'Phút', exact: true }).getByRole('button').allTextContents(), ['10']);
    await popup.getByRole('button', { name: 'Chọn 09:10', exact: true }).click();
    assert.equal(await datetime.inputValue(), '2026-11-19T09:10');
    assert.equal(await datetime.evaluate(input => input.validity.valid), true);
    await page.getByLabel('Chỉ đọc', { exact: true }).click();
    assert.equal(await popup.count(), 0);
    const select = page.locator('#control-fixture > label select');
    await select.focus(); await page.keyboard.press('ArrowDown');
    await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
    assert.equal(await select.inputValue(), 'c', 'keyboard skips disabled option');
    await select.click();
    await page.screenshot({ path: `${folder}/select-${width}.png` });
    const geometry = await popup.evaluate(panel => { const rect = panel.getBoundingClientRect(); return { left: rect.left, right: rect.right, top: rect.top, bottom: rect.bottom, radius: getComputedStyle(panel).borderRadius }; });
    assert.ok(geometry.left >= 0 && geometry.right <= width && geometry.top >= 0 && geometry.bottom <= 900, JSON.stringify(geometry));
    assert.equal(geometry.radius, '20px');
    await page.keyboard.press('Escape');
    await stepped.click();
    await popup.getByRole('button', { name: '20/11/2026', exact: true }).focus();
    await page.keyboard.press('ArrowRight'); // next day is disabled and must not be chosen
    assert.equal(await stepped.inputValue(), '2026-11-20');
    await page.keyboard.press('Escape');
    await birth.click();
    await page.evaluate(() => document.getElementById('control-fixture').remove());
    await popup.waitFor({ state: 'detached' });
    assert.deepEqual(errors, []);
    assert.deepEqual(writes, []);
    report.push({ width, errors, writes, geometry, status: 'PASS' });
    await context.close();
    console.log(`PASS ${width}: React forms, birthday/year, min/max/step, time/datetime, clear/required, keyboard, rounded select, viewport, no API writes`);
  }
  await writeFile(`${folder}/report.json`, JSON.stringify(report, null, 2));
} finally { await browser.close(); }
